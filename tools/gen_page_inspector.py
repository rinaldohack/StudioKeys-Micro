def resolve(tok: str, scope: str) -> int:
    tok = tok.strip()
    if tok in ("0xFF", "0xff"):
        return 255
    if tok.isdigit():
        return int(tok)
    if tok.startswith("P_") and tok in P:
        return P[tok]
    if tok.startswith("G_") and tok in G:
        return G[tok]
    # step/mixer slot indices stay as small ints
    raise SystemExit(f"unknown id {tok!r} scope={scope}")


def main() -> int:
    text = PARAMS.read_text()
    m = re.search(r"static const page_t PAGES\[\] = \{(.*?)\n\};", text, re.S)
    if not m:
        print("PAGES[] not found", file=sys.stderr)
        return 1
    rows = re.findall(
        r'\{\s*"([^"]+)"\s*,\s*(FAM_\w+)\s*,\s*(SC_\w+)\s*,\s*(GR_\w+)\s*,\s*\{([^}]+)\}\s*\}',
        m.group(1),
    )
    lines = [
        "// Auto-generated by tools/gen_page_inspector.py — do not edit by hand.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace skpages {",
        "",
        "enum Fam : uint8_t {",
        "  FAM_HOME=0, FAM_ENV, FAM_LFO, FAM_FX, FAM_SCL, FAM_EDIT, FAM_GLO, FAM_SAVE, FAM_ARP, FAM_SEQ, FAM_TRK",
        "};",
        "enum Scope : uint8_t { SC_TRACK=0, SC_GLOBAL, SC_ENGINE, SC_STEP, SC_TRK };",
        "",
        "struct Page {",
        "  const char* title;",
        "  uint8_t fam;",
        "  uint8_t scope;",
        "  uint8_t ids[8]; /* 255 = empty */",
        "};",
        "",
        "static constexpr Page kPages[] = {",
    ]
    fam_map = {
        "FAM_HOME": 0, "FAM_ENV": 1, "FAM_LFO": 2, "FAM_FX": 3, "FAM_SCL": 4,
        "FAM_EDIT": 5, "FAM_GLO": 6, "FAM_SAVE": 7, "FAM_ARP": 8, "FAM_SEQ": 9, "FAM_TRK": 10,
    }
    scope_map = {
        "SC_TRACK": 0, "SC_GLOBAL": 1, "SC_ENGINE": 2, "SC_STEP": 3, "SC_TRK": 4,
    }
    for title, fam, scope, _gr, ids in rows:
        parts = [p.strip() for p in ids.split(",")]
        nums = [resolve(p, scope) for p in parts]
        while len(nums) < 8:
            nums.append(255)
        nums = nums[:8]
        lines.append(
            f'  {{"{title}", {fam_map[fam]}, {scope_map[scope]}, '
            f"{{{', '.join(str(n) for n in nums)}}}}},"
        )
    # Short labels from params.c TP/GP for inspector chrome (ids only; live host
    # labels win via sk_host_page_param_label when the host is linked).
    p_labels = {v: k[2:] if k.startswith("P_") else k for k, v in P.items()}
    g_labels = {v: k[2:] if k.startswith("G_") else k for k, v in G.items()}
    lines += [
        "};",
        "",
        f"static constexpr int kNumPages = {len(rows)};",
        "",
        "inline const char* TrackLabel(uint8_t id) {",
        "  switch (id) {",
    ]
    for i in sorted(p_labels):
        if i > 90:
            continue
        lines.append(f'    case {i}: return "{p_labels[i]}";')
    lines += [
        '    default: return "";',
        "  }",
        "}",
        "",
        "inline const char* GlobalLabel(uint8_t id) {",
        "  switch (id) {",
    ]
    for i in sorted(g_labels):
        lines.append(f'    case {i}: return "{g_labels[i]}";')
    lines += [
        '    default: return "";',
        "  }",
        "}",
        "",
        "inline int FindPage(const char* title) {",
        "  if (!title) return -1;",
        "  for (int i = 0; i < kNumPages; ++i)",
        "    if (kPages[i].title[0] && title[0] && !__builtin_strcmp(kPages[i].title, title))",
        "      return i;",
        "  return -1;",
        "}",
        "",
        "} // namespace skpages",
        "",
    ]
    # Use strcmp instead of __builtin for MSVC
    body = "\n".join(lines).replace(
        "!__builtin_strcmp(kPages[i].title, title)",
        "std::strcmp(kPages[i].title, title) == 0",
    )
    body = body.replace("#include <cstdint>", "#include <cstdint>\n#include <cstring>")
    OUT.write_text(body)
    print(f"wrote {OUT} ({len(rows)} pages)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
