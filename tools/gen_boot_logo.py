"""The boot splash's LangitCinta! mark -> firmware/src/lc_boot_logo.h.

The boot screen (bootanim.c) draws the mark alone for a second, at 176 x 187 on the 240 x 240
panel: native pixels, 4-bit coverage, in the artwork's own 642:682 ratio, so it reads as the mark
rather than as a scaled-up icon. The old 39 x 48 asset (lc_logo.h, still the menu's mark) was drawn
3x nearest-neighbour at 39:48, which is what made the splash look blocky and too wide.

Storage: the nibble stream goes through the same canonical-Huffman coder the AA fonts use
(tools/gen_aa_font.py huff_pack; gfx.c cv_alpha_hc decodes it), so the image costs ~1.3 bits per
pixel instead of 4: 5.2 KB in flash for the whole mark. The panel canvas (CV_MAX = 240 x 124) is
shorter than the mark, so it is coded in two strips, each an independent bit stream, and blitted
one under the other.

    tools/gen_boot_logo.py [--src PNG] [--width 176] [--out firmware/src/lc_boot_logo.h]
    tools/gen_boot_logo.py --preview            # also write build/boot_splash/logo.png at 1:1

The header is checked in, as lc_logo.h is: the firmware build needs the generated bytes, not
Pillow and not the PNG. Re-run this after replacing assets/logo/langitcinta.png."""
import argparse
import os
import sys

from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_aa_font import HC_MAXLEN, huff_pack, huff_unpack          # noqa: E402

STRIP_ROWS = 124        # CV_MAX / 208: the tallest canvas the boot screen can blit at a time
PANEL = 240
INK_MIN = 8             # the faintest alpha that survives the 4-bit quantiser (v >= 1 from 8 on)


def load(path):
    """the mark's coverage, cropped to its ink: alpha >= INK_MIN (the asset carries alpha 1..7 specks
    out to the right edge, and cropping to those would shrink the mark by a fifth)"""
    im = Image.open(path).convert("RGBA")
    ink = im.split()[-1]
    box = ink.point(lambda v: 255 if v >= INK_MIN else 0).getbbox()
    if not box:
        sys.exit(f"{path}: no ink (every pixel under alpha {INK_MIN})")
    return ink.crop(box)


def quantise(ink, width):
    h = max(1, round(width * ink.size[1] / ink.size[0]))
    small = ink.resize((width, h), Image.LANCZOS)
    return [min(15, (v * 15 + 127) // 255) for v in small.tobytes()], h


def emit(path, src, w, h, rows0, hc, strips):
    strips = [bytes(s) + b"\0\0" for s in strips]     # cv_alpha_hc refills 16 bits at a time: 2 spare
    total = len(hc) + sum(len(s) for s in strips)

    def arr(name, data):
        out = [f"static const uint8_t {name}[] = {{"]
        for i in range(0, len(data), 12):
            out.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 12]) + ",")
        out[-1] = out[-1].rstrip(",")
        out.append("};")
        return "\n".join(out)

    text = f"""/* SPDX-License-Identifier: GPL-3.0-only
 * Copyright (C) 2026 Rinaldo Jonathan (LangitCinta! StageLabs) */
/* The boot splash's mark: the LangitCinta! logo at {w} x {h}, 4-bit coverage, Huffman-coded the way
 * the AA faces are (gen_aa_font.py huff_pack; gfx.c cv_alpha_hc reads it). Generated by
 * tools/gen_boot_logo.py from {src} - do not edit by hand; re-run the tool instead.
 *
 * {total} B: {len(hc)} of code lengths and symbols, then the two strips ({', '.join(str(len(s)) for s in strips)} B),
 * because the blit canvas holds {STRIP_ROWS} rows at this width. Draw with boot_screen() (bootanim.c). */
#pragma once
#include <stdint.h>

#define LC_BOOT_LOGO_W      {w}u
#define LC_BOOT_LOGO_H      {h}u
#define LC_BOOT_LOGO_ROWS0  {rows0}u        /* rows in the first strip; the rest is the second */

{arr("LC_BOOT_LOGO_HC", hc)}

{arr("LC_BOOT_LOGO_S0", strips[0])}

{arr("LC_BOOT_LOGO_S1", strips[1])}
"""
    with open(path, "w") as f:
        f.write(text)
    return total


def main():
    ap = argparse.ArgumentParser()
    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    ap.add_argument("--src", default=os.path.join(here, "assets/logo/langitcinta.png"))
    ap.add_argument("--out", default=os.path.join(here, "firmware/src/lc_boot_logo.h"))
    ap.add_argument("--width", type=int, default=176, help="pixels wide on the 240 px panel")
    ap.add_argument("--preview", action="store_true")
    a = ap.parse_args()

    ink = load(a.src)
    vals, h = quantise(ink, a.width)
    if a.width > PANEL or h > PANEL:
        sys.exit(f"{a.width} x {h} does not fit the {PANEL} x {PANEL} panel")

    rows0 = min(STRIP_ROWS, h)
    strips = [vals[0:rows0 * a.width], vals[rows0 * a.width:]]
    hc, data = huff_pack(strips)
    total = emit(a.out, os.path.relpath(a.src, here), a.width, h, rows0, hc, data)

    # the self-check: decode the emitted streams exactly as gfx.c does
    for k, (src, n) in enumerate(zip(strips, (len(s) for s in strips))):
        got = huff_unpack(hc, data[k], n)
        if got != src:
            sys.exit(f"strip {k}: decoded {len(got)} values do not match the quantised image")
    print(f"boot logo: {a.width} x {h} from {ink.size[0]} x {ink.size[1]} ink, {total} B "
          f"(hc {len(hc)}, strips {', '.join(str(len(d)) for d in data)}), round-trip ok -> {a.out}")

    if a.preview:
        path = os.path.join(here, "build/boot_splash/logo.png")
        os.makedirs(os.path.dirname(path), exist_ok=True)
        im = Image.new("RGB", (PANEL, PANEL), (0, 12, 24))
        mask = Image.new("L", (a.width, h))
        mask.putdata([v * 17 for v in vals])
        im.paste(Image.new("RGB", (a.width, h), (255, 255, 255)),
                 ((PANEL - a.width) // 2, (PANEL - h) // 2), mask)
        im.save(path)
        print(f"preview: {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
