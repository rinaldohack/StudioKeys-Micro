/* ---------------------------------------------------- build options --- */
/* build.py: SKM_<NAME>=0 / 1 in the environment overrides these. Elsewhere: SKM_SLICE, SKM_FM4
 * (core.h: the SLICE engine, the DIGITAL engine), SKM_ICONS (icons.c, the parameter icons; on by default),
 * SKM_OTA_RAMONLY (ota.c). */
#ifndef SKM_FLASH
#define SKM_FLASH 1          /* flash driver + storage.c: settings, projects, user presets */
#define SKM_ON_DEVICE 1      /* host tests leave this unset */
#endif
#ifndef SKM_OTA
#define SKM_OTA 1            /* M-UPGRADE update entry and the editor SysEx; needs SKM_FLASH */
#endif
#ifndef SKM_OTA_DRYRUN
#define SKM_OTA_DRYRUN 0     /* 1 = stage, ask "success", then undo: no record, no reset */
#endif
#ifndef SKM_CDC
#define SKM_CDC 1            /* USB CDC-ACM serial console */
#endif
#ifndef SKM_UAC
#define SKM_UAC 1            /* USB audio input: the master output, 16-bit stereo 44.1 kHz (usb.c) */
#endif
#ifndef SKM_UAC_TONE
#define SKM_UAC_TONE 0       /* bench: the USB input sends test triangles instead of the music */
#endif
#ifndef SKM_UART
#define SKM_UART 0           /* SMK-37 has MIDI OUT only. PH8 is a matrix row. */
#endif
#ifndef SKM_ID
#define SKM_ID "SKM_1001"    /* package identity (build.py overrides this with the same string) */
#endif
#define SK_USB_VID 0x4353u       /* M-VAVE, the Elite's vendor */
#define SKM_USB_PID 0x4B4Du  /* Elite product id */
#define SK_PRODUCT 1
#define SK_MIDI_PORTS 4          /* cable 0 perf, 1 Live, 2 HUI, 3 plugin link */
#ifndef SKM_VERSION
#define SKM_VERSION "v1.0.0" /* public release; the editor and the companion VST must match */
#endif
#if SKM_OTA && !SKM_FLASH
#error "SKM_OTA needs SKM_FLASH"
#endif

